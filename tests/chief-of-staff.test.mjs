test("Chief of Staff plans persist and final consolidation receives every dependency output", async (t) => {
  const client = createClient({ url: "file::memory:" });
  await migrateExecutionSchema(client);
  t.after(async () => { await client.close(); });
  const plan = await planChiefOfStaff({ instruction: "Review feedback and prepare an update", planningMode: "live" }, {
    agents: capabilities,
    generateLivePlan: async () => liveOutput(),
  });
  const executionInput = toExecutionRunInput({
    name: "Customer update",
    concurrencyLimit: 2,
    executionMode: "mock",
    originalInstruction: "Review feedback and prepare an update",
    planningMode: "live",
    plan,
  });
  const run = await createExecutionRun(client, executionInput);
  assert.equal(run.originalInstruction, "Review feedback and prepare an update");
  assert.equal(run.planningMode, "live");
  assert.match(run.planningRationale, /evidence gathering/);
  const received = new Map();
  const executor = {
    retrySafety: "never",
    execute: async (task, context) => {
      received.set(task.title, context.dependencies);
      return { title: task.title, result: `Output from ${task.title}` };
    },
  };
  await startExecutionRun(client, run.id, executor);
  let settled;
  const deadline = Date.now() + 3000;
  do {
    await new Promise((resolve) => setTimeout(resolve, 10));
    settled = await getExecutionRun(client, run.id);
  } while (!["completed", "failed", "cancelled"].includes(settled.status) && Date.now() < deadline);
  assert.equal(settled.status, "completed");
  const finalTask = settled.tasks.find((task) => task.title === "Consolidate the final deliverable");
  const finalDependencies = received.get(finalTask.title);
  assert.equal(finalDependencies.length, 2);
  assert.ok(finalDependencies.every((dependency) => dependency.output.result.startsWith("Output from ")));
  assert.match(buildExecutionPrompt(finalTask, finalDependencies), /final consolidation task/i);
  assert.match(buildExecutionPrompt(finalTask, finalDependencies), /Output from Review customer feedback/);
});

test("owner-selected agent list restricts live generation and rejects out-of-roster assignments", async () => {
  const input = { instruction: "Prepare a customer update", planningMode: "live", agentIds: ["writer"] };
  const result = await planChiefOfStaff(input, { agents: capabilities, generateLivePlan: async ({ agents }) => {
    assert.deepEqual(agents.map((agent) => agent.id), ["writer"]);
    const output = liveOutput();
    return { ...output, tasks: output.tasks.map((task) => ({ ...task, agentId: "writer" })) };
  } });
  assert.ok(result.tasks.every((task) => task.agentId === "writer"));
  await assert.rejects(planChiefOfStaff(input, { agents: capabilities, generateLivePlan: async () => liveOutput() }));
  await assert.rejects(planChiefOfStaff({ ...input, agentIds: ["missing"] }, { agents: capabilities, generateLivePlan: async () => { throw new Error("should not call model"); } }), /selected agents/);
});
