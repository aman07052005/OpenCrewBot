test("mock plans preserve long original instructions without duplicating them into bounded task instructions", async () => {
  const instruction = `Prepare a useful business brief. ${"Include the full context and constraints. ".repeat(260)}`;
  const plan = await planChiefOfStaff({ instruction, planningMode: "mock" }, { agents: capabilities });
  const executionInput = toExecutionRunInput({
    name: "Long brief",
    concurrencyLimit: 1,
    executionMode: "mock",
    originalInstruction: instruction,
    planningMode: "mock",
    plan,
  });
  assert.ok(instruction.length > 8_000);
  assert.ok(plan.tasks.every((task) => task.instructions.length <= 8_000));
  assert.equal(executionInput.originalInstruction, instruction);
  assert.ok(executionInput.tasks.every((task) => task.input.originalInstruction === instruction));
});

